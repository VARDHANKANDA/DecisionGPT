"""Reproducible comparison of five forecasting algorithms on datasets with a defensible target.

Target (stated per dataset, nothing invented):
  * ``pos_daily_revenue``  - total rupee value of one day's sales lines in a real Indian POS register (89 days).
  * ``platform_units``     - units sold per series per day in the SYNTHETIC platform forecasting set (labelled synthetic).

Task: one-day-ahead prediction. Every feature for day t is computed from days <= t-1 (lags / shifted rolling means) or is a calendar
attribute of t itself; price / marketing / promotion in the synthetic set are the planned values for day t. The target never enters
its own row's features.

Controls: chronological 70/15/15 split on unique dates (the last 15% is an untouched test period used once, after selection),
expanding-window TimeSeriesSplit(3) over train+val for model selection, scalers fitted inside each training fold only, fixed seed,
no hyper-parameter tuning (fixed documented parameters), a seasonal-naive baseline every learned model must beat, versioned JSON
record per run under ``experiments/model_comparison_v1/``.
"""
from __future__ import annotations

import hashlib
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import HistGradientBoostingRegressor, RandomForestRegressor
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.model_selection import TimeSeriesSplit
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parents[3]
RESULTS_DIR = ROOT / "experiments" / "model_comparison_v1"
POS_CSV = ROOT / "data" / "external" / "india_pos_register" / "processed" / "india_pos_register_clean.csv"
PLATFORM_CSV = ROOT / "data" / "platform" / "forecasting" / "sales_timeseries.csv"

SEED = 42
TRAIN_FRAC, VAL_FRAC = 0.70, 0.15
CV_SPLITS = 3
INTERVAL_ALPHA = 0.20  # 80% split-conformal interval
MIN_TEST_DATES = 5
MIN_TRAIN_DATES = 30
BOOTSTRAP_DRAWS = 2000

DATASETS = {
    "pos_daily_revenue": {
        "name": "Indian POS register - daily revenue",
        "provenance": "real",
        "source": "data/external/india_pos_register (Kaggle retail-sales-register, CC BY-NC-SA 4.0; provenance not independently verified)",
        "target": "daily revenue (INR) = sum of line_amount_inr over sales lines with qty > 0, whole-number qty and amount equal to the printed amount",
        "unit": "INR per day",
    },
    "platform_units": {
        "name": "Synthetic D2C platform - daily units per series",
        "provenance": "synthetic",
        "source": "data/platform/forecasting/sales_timeseries.csv (generated by scripts/generate_platform_data.py)",
        "target": "units_sold per series per day",
        "unit": "units per series-day",
    },
}


# ------------------------------------------------------------------------------------------------ data
def load_pos_daily(path: Path | None = None) -> tuple[pd.DataFrame, dict]:
    raw = pd.read_csv(path or POS_CSV)
    need = {"date", "qty", "line_amount_inr", "amount_matches_printed"}
    missing = need - set(raw.columns)
    if missing:
        raise ValueError(f"POS file is missing columns {sorted(missing)}")
    raw["date"] = pd.to_datetime(raw["date"], errors="coerce")
    n0 = len(raw)
    bad_date = int(raw["date"].isna().sum())
    ok = raw["date"].notna() & (raw["qty"] > 0) & (raw["qty"] % 1 == 0) & raw["amount_matches_printed"].astype(bool)
    kept = raw[ok]
    daily = kept.groupby("date", as_index=False)["line_amount_inr"].sum().rename(columns={"line_amount_inr": "y"})
    full = pd.date_range(daily["date"].min(), daily["date"].max(), freq="D")
    daily = daily.set_index("date").reindex(full).rename_axis("date").reset_index()  # a missing day stays NaN: never imputed
    daily["series_id"] = "pos"
    info = {"rows_in": n0, "rows_with_invalid_date": bad_date, "rows_kept": int(ok.sum()), "rows_excluded": int(n0 - ok.sum()),
            "exclusion_rule": "qty<=0, non-integer qty, or amount differs from the printed amount",
            "calendar_days": int(len(full)), "days_with_sales": int(daily["y"].notna().sum()),
            "missing_dates": [d.strftime("%Y-%m-%d") for d in daily.loc[daily["y"].isna(), "date"]]}
    return daily[["series_id", "date", "y"]], info


def load_platform(path: Path | None = None) -> tuple[pd.DataFrame, dict]:
    raw = pd.read_csv(path or PLATFORM_CSV)
    need = {"series_id", "date", "units_sold", "price", "marketing_spend", "promotion_flag"}
    missing = need - set(raw.columns)
    if missing:
        raise ValueError(f"platform file is missing columns {sorted(missing)}")
    raw["date"] = pd.to_datetime(raw["date"], errors="coerce")
    df = raw.rename(columns={"units_sold": "y"})
    info = {"rows_in": int(len(raw)), "rows_with_invalid_date": int(raw["date"].isna().sum()), "series": int(raw["series_id"].nunique()),
            "exact_duplicate_keys": int(raw.duplicated(["series_id", "date"]).sum())}
    return df[["series_id", "date", "y", "price", "marketing_spend", "promotion_flag"]].dropna(subset=["date"]), info


def make_features(df: pd.DataFrame, with_covariates: bool) -> tuple[pd.DataFrame, list[str]]:
    """Leakage-safe features. Lags and rolling means are shifted so day t sees only days <= t-1."""
    d = df.sort_values(["series_id", "date"]).copy()
    g = d.groupby("series_id")["y"]
    d["lag_1"] = g.shift(1)
    d["lag_7"] = g.shift(7)
    d["rolling_mean_7"] = g.transform(lambda s: s.shift(1).rolling(7, min_periods=5).mean())
    feats = ["lag_1", "lag_7", "rolling_mean_7"]
    if with_covariates:
        d["rolling_mean_28"] = g.transform(lambda s: s.shift(1).rolling(28, min_periods=20).mean())
        feats.append("rolling_mean_28")
    dow = d["date"].dt.dayofweek
    for k in range(7):
        d[f"dow_{k}"] = (dow == k).astype(int)
    feats += [f"dow_{k}" for k in range(7)]
    if with_covariates:
        feats += ["price", "marketing_spend", "promotion_flag"]
    usable = d.dropna(subset=["y"] + feats).reset_index(drop=True)
    return usable, feats


def split_dates(dates: list, train_frac: float = TRAIN_FRAC, val_frac: float = VAL_FRAC) -> dict[str, list]:
    n = len(dates)
    i1, i2 = int(n * train_frac), int(n * (train_frac + val_frac))
    return {"train": dates[:i1], "val": dates[i1:i2], "test": dates[i2:]}


# ------------------------------------------------------------------------------------------------ metrics
def regression_metrics(y_true, y_pred) -> dict[str, Any]:
    y = np.asarray(y_true, dtype=float)
    p = np.asarray(y_pred, dtype=float)
    n = int(len(y))
    err = p - y
    out: dict[str, Any] = {"n": n, "mae": float(np.mean(np.abs(err))), "rmse": float(np.sqrt(np.mean(err**2))), "bias": float(np.mean(err))}
    ss_tot = float(np.sum((y - y.mean()) ** 2))
    if n >= 3 and ss_tot > 0:
        out["r2"] = float(1 - np.sum(err**2) / ss_tot)
        out["r2_note"] = "negative values mean worse than predicting the test-period mean"
    else:
        out["r2"] = None
        out["r2_note"] = "undefined: fewer than 3 points or no variation in the target"
    a = np.abs(y)
    if n and a.min() > 0 and a.min() / a.mean() >= 0.1:
        out["mape_pct"] = float(np.mean(np.abs(err) / a) * 100)
        out["mape_note"] = None
    else:
        out["mape_pct"] = None
        out["mape_note"] = "not reported: target values at or near zero make percentage error misleading"
    return out


# ------------------------------------------------------------------------------------------------ models
def build_models(seed: int) -> dict[str, dict]:
    return {
        "linear_regression": {"label": "Linear Regression", "estimator": lambda: make_pipeline(StandardScaler(), LinearRegression()),
                              "params": {"scaler": "StandardScaler fitted on training rows only", "fit_intercept": True}},
        "ridge_regression": {"label": "Ridge Regression", "estimator": lambda: make_pipeline(StandardScaler(), Ridge(alpha=1.0)),
                             "params": {"scaler": "StandardScaler fitted on training rows only", "alpha": 1.0}},
        "random_forest": {"label": "Random Forest", "estimator": lambda: RandomForestRegressor(n_estimators=300, min_samples_leaf=2, random_state=seed, n_jobs=1),
                          "params": {"n_estimators": 300, "min_samples_leaf": 2, "random_state": seed}},
        "hist_gradient_boosting": {"label": "Gradient Boosting (HistGradientBoosting)",
                                   "estimator": lambda: HistGradientBoostingRegressor(max_iter=200, learning_rate=0.05, max_depth=4, random_state=seed),
                                   "params": {"max_iter": 200, "learning_rate": 0.05, "max_depth": 4, "random_state": seed}},
    }


BASELINE_KEY = "seasonal_naive_7"
BASELINE_LABEL = "Seasonal naive (same weekday last week)"


def _bootstrap_mae_diff(dates: np.ndarray, err_model: np.ndarray, err_base: np.ndarray, seed: int) -> dict[str, Any]:
    """Paired bootstrap over test DATES (clusters), difference in mean absolute error, model minus baseline."""
    uniq = np.unique(dates)
    idx_by = {d: np.where(dates == d)[0] for d in uniq}
    rng = np.random.default_rng(seed)
    diffs = []
    for _ in range(BOOTSTRAP_DRAWS):
        pick = rng.choice(len(uniq), size=len(uniq), replace=True)
        rows = np.concatenate([idx_by[uniq[i]] for i in pick])
        diffs.append(float(np.mean(np.abs(err_model[rows])) - np.mean(np.abs(err_base[rows]))))
    lo, hi = np.percentile(diffs, [2.5, 97.5])
    return {"mean_abs_error_diff_model_minus_baseline": float(np.mean(np.abs(err_model)) - np.mean(np.abs(err_base))),
            "ci95": [float(lo), float(hi)], "resampling_unit": "test date", "draws": BOOTSTRAP_DRAWS, "seed": seed,
            "reading": "negative = model has lower error than the baseline; an interval containing 0 means no reliable difference at this sample size"}


# ------------------------------------------------------------------------------------------------ run
def run_dataset(key: str, seed: int = SEED, df_override: pd.DataFrame | None = None, load_info: dict | None = None) -> dict[str, Any]:
    if key not in DATASETS:
        raise ValueError(f"unknown dataset {key!r}")
    meta = DATASETS[key]
    covariates = key == "platform_units"
    if df_override is not None:
        raw, info = df_override, (load_info or {})
    else:
        raw, info = load_pos_daily() if key == "pos_daily_revenue" else load_platform()
    data, feats = make_features(raw, covariates)
    base = {"dataset_key": key, "dataset": meta, "dataset_load": info, "seed": seed}

    dates = sorted(data["date"].unique())
    parts = split_dates(dates)
    if len(parts["train"]) < MIN_TRAIN_DATES or len(parts["test"]) < MIN_TEST_DATES:
        return {**base, "status": "insufficient_data",
                "reason": f"{len(parts['train'])} training dates and {len(parts['test'])} test dates after feature construction; need at least "
                          f"{MIN_TRAIN_DATES} and {MIN_TEST_DATES}. No benchmark was produced."}

    part = {k: data[data["date"].isin(set(v))] for k, v in parts.items()}
    trval = pd.concat([part["train"], part["val"]]).sort_values(["date", "series_id"]).reset_index(drop=True)
    test = part["test"].sort_values(["date", "series_id"]).reset_index(drop=True)
    X_tv, y_tv, X_te, y_te = trval[feats], trval["y"].to_numpy(), test[feats], test["y"].to_numpy()

    # expanding-window CV over unique train+val dates
    tv_dates = np.array(sorted(trval["date"].unique()))
    folds = []
    for tr_i, va_i in TimeSeriesSplit(n_splits=CV_SPLITS).split(tv_dates):
        tr_mask = trval["date"].isin(set(tv_dates[tr_i])).to_numpy()
        va_mask = trval["date"].isin(set(tv_dates[va_i])).to_numpy()
        folds.append((tr_mask, va_mask, str(tv_dates[tr_i][0])[:10], str(tv_dates[tr_i][-1])[:10], str(tv_dates[va_i][0])[:10], str(tv_dates[va_i][-1])[:10]))

    models = build_models(seed)
    results: dict[str, Any] = {}
    oof_resid: dict[str, list[float]] = {}
    for mk, spec in models.items():
        fold_rmse, fold_mae, fold_r2, resid = [], [], [], []
        for tr_mask, va_mask, *_ in folds:
            est = spec["estimator"]()
            est.fit(X_tv[tr_mask], y_tv[tr_mask])
            p = est.predict(X_tv[va_mask])
            met = regression_metrics(y_tv[va_mask], p)
            fold_rmse.append(met["rmse"])
            fold_mae.append(met["mae"])
            if met.get("r2") is not None:
                fold_r2.append(met["r2"])
            resid += list(np.abs(y_tv[va_mask] - p))
        oof_resid[mk] = resid
        val_r2 = float(np.mean(fold_r2)) if fold_r2 else None
        results[mk] = {
            "label": spec["label"],
            "params": spec["params"],
            "cv_rmse_per_fold": fold_rmse,
            "cv_rmse_mean": float(np.mean(fold_rmse)),
            "cv_rmse_sd": float(np.std(fold_rmse)),
            "validation": {
                "rmse": float(np.mean(fold_rmse)),
                "mae": float(np.mean(fold_mae)),
                "r2": val_r2,
                "r2_note": "mean R² over train+val expanding-window cross-validation folds",
            },
        }
    # baseline: the same weekday last week, taken from the observed series (lag_7)
    base_rmse, base_mae, base_r2 = [], [], []
    for _, va, *_ in folds:
        b_met = regression_metrics(y_tv[va], X_tv["lag_7"].to_numpy()[va])
        base_rmse.append(b_met["rmse"])
        base_mae.append(b_met["mae"])
        if b_met.get("r2") is not None:
            base_r2.append(b_met["r2"])
    results[BASELINE_KEY] = {
        "label": BASELINE_LABEL,
        "params": {"rule": "prediction = value 7 days earlier"},
        "cv_rmse_per_fold": base_rmse,
        "cv_rmse_mean": float(np.mean(base_rmse)),
        "cv_rmse_sd": float(np.std(base_rmse)),
        "validation": {
            "rmse": float(np.mean(base_rmse)),
            "mae": float(np.mean(base_mae)),
            "r2": float(np.mean(base_r2)) if base_r2 else None,
            "r2_note": "mean R² over train+val expanding-window cross-validation folds",
        },
    }

    selected = min(models, key=lambda m: results[m]["cv_rmse_mean"])  # selection uses train+val CV only, never the test period

    # refit on train+val, evaluate once on the untouched test period
    preds: dict[str, np.ndarray] = {BASELINE_KEY: X_te["lag_7"].to_numpy()}
    for mk, spec in models.items():
        est = spec["estimator"]()
        est.fit(X_tv, y_tv)
        preds[mk] = est.predict(X_te)
    for mk, p in preds.items():
        results[mk]["test"] = regression_metrics(y_te, p)
    base_t = results[BASELINE_KEY]["test"]
    for mk in models:
        t = results[mk]["test"]
        t["rmse_change_vs_baseline_pct"] = float((t["rmse"] / base_t["rmse"] - 1) * 100) if base_t["rmse"] > 0 else None
        t["beats_baseline_on_test_rmse"] = bool(t["rmse"] < base_t["rmse"])
        results[mk]["paired_vs_baseline"] = _bootstrap_mae_diff(test["date"].to_numpy(), preds[mk] - y_te, preds[BASELINE_KEY] - y_te, seed)

    # forecast uncertainty of the selected model: split-conformal 80% interval from out-of-fold residuals
    r = np.sort(np.asarray(oof_resid[selected]))
    k = int(np.ceil((len(r) + 1) * (1 - INTERVAL_ALPHA)))
    q = float(r[min(k, len(r)) - 1])
    inside = np.abs(y_te - preds[selected]) <= q
    uncertainty = {"model": selected, "method": "split-conformal on out-of-fold absolute residuals (train+val)", "nominal_coverage": 1 - INTERVAL_ALPHA,
                   "interval_half_width": q, "calibration_residuals": int(len(r)), "test_points": int(len(y_te)),
                   "empirical_coverage_test": float(np.mean(inside)), "mean_interval_width": float(2 * q),
                   "reading": "with this few test points, coverage differs from nominal by chance; read it as indicative"}

    by_date = (test.assign(pred=preds[selected], err=preds[selected] - y_te).groupby("date")["err"]
               .apply(lambda s: float(np.mean(np.abs(s)))).reset_index().rename(columns={"err": "mean_abs_error"}))
    checks = {
        "train_before_val_before_test": bool(max(parts["train"]) < min(parts["val"]) <= max(parts["val"]) < min(parts["test"])),
        "target_not_in_features": "y" not in feats,
        "features_use_only_past_values": "lag_1, lag_7 and rolling means are shifted by at least one day before use",
        "duplicate_series_date_keys": int(raw.duplicated(["series_id", "date"]).sum()),
        "missing_values_in_target_before_feature_drop": int(raw["y"].isna().sum()),
        "rows_dropped_for_missing_features_or_target": int(len(raw) - len(data)),
    }
    cfg = {"dataset": key, "seed": seed, "features": feats, "split": [TRAIN_FRAC, VAL_FRAC], "cv": CV_SPLITS, "models": {m: results[m]["params"] for m in models}}
    created = datetime.now(timezone.utc)
    return {
        **base, "status": "completed",
        "run_id": f"mc_{created.strftime('%Y%m%dT%H%M%SZ')}_{key}_{hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest()[:8]}",
        "created_utc": created.isoformat(timespec="seconds"),
        "evidence_type": "measured" if meta["provenance"] == "real" else "measured_on_synthetic_data",
        "task": "one-day-ahead forecast of the target",
        "n_usable_observations": int(len(data)), "n_dates": int(len(dates)),
        "period": {"first": str(dates[0])[:10], "last": str(dates[-1])[:10]},
        "features": feats,
        "split": {k: {"first": str(v[0])[:10], "last": str(v[-1])[:10], "dates": len(v), "rows": int(len(part[k]))} for k, v in parts.items()},
        "cv": {"scheme": f"expanding-window TimeSeriesSplit({CV_SPLITS}) over train+val dates",
               "folds": [{"train": [f[2], f[3]], "validate": [f[4], f[5]]} for f in folds]},
        "baseline": {"key": BASELINE_KEY, "label": BASELINE_LABEL},
        "models": results,
        "selection": {"rule": "lowest mean cross-validated RMSE over train+val folds among the four learned models (test period not used)",
                      "selected": selected, "selected_label": results[selected]["label"],
                      "test": results[selected]["test"],
                      "beats_baseline_on_test_rmse": results[selected]["test"]["beats_baseline_on_test_rmse"]},
        "uncertainty": uncertainty,
        "test_error_by_date": [{"date": str(r_["date"])[:10], "mean_abs_error": r_["mean_abs_error"]} for _, r_ in by_date.iterrows()],
        "checks": checks,
        "reproducibility": {"seed": seed, "python": platform.python_version(), "numpy": np.__version__, "pandas": pd.__version__, "scikit_learn": sklearn.__version__,
                            "platform": platform.platform(), "config_sha256": hashlib.sha256(json.dumps(cfg, sort_keys=True).encode()).hexdigest()},
        "limitations": _limitations(key, len(parts["test"]), len(dates)),
    }


def _limitations(key: str, n_test_dates: int, n_dates: int) -> list[str]:
    out = [f"Test period has {n_test_dates} dates (of {n_dates}); error estimates are indicative, not precise.",
           "Fixed model parameters were used (no tuning), so a different configuration could rank differently.",
           "One chronological split; no repeated-origin backtest, so performance over other periods is unknown.",
           "No claim of statistical superiority is made: the paired bootstrap interval is reported, and an interval containing 0 means no reliable difference."]
    if key == "pos_daily_revenue":
        out.append("Single store, 89 days, one missing date; not representative of Indian SMEs or Indian retail generally.")
    else:
        out.append("Synthetic data generated by the project; results describe the generator, not real businesses.")
    return out


def run_all(seed: int = SEED, save: bool = True) -> dict[str, Any]:
    out = {}
    for key in DATASETS:
        try:
            res = run_dataset(key, seed)
        except FileNotFoundError as exc:
            res = {"dataset_key": key, "dataset": DATASETS[key], "status": "blocked", "reason": f"data file not found: {exc.filename}"}
        except Exception as exc:  # noqa: BLE001 - recorded, never hidden
            res = {"dataset_key": key, "dataset": DATASETS[key], "status": "failed", "reason": f"{type(exc).__name__}: {exc}"[:300]}
        if save and res.get("status") == "completed":
            RESULTS_DIR.mkdir(parents=True, exist_ok=True)
            d = RESULTS_DIR / res["run_id"]
            d.mkdir(parents=True, exist_ok=False)
            (d / "results.json").write_text(json.dumps(res, indent=2, default=str), encoding="utf-8")
        out[key] = res
    return out


# ------------------------------------------------------------------------------------------------ read side
def latest_results() -> dict[str, Any]:
    """Latest stored completed run per dataset, plus the datasets that have none. Reads files only; never runs anything."""
    found: dict[str, dict] = {}
    if RESULTS_DIR.exists():
        for p in sorted(RESULTS_DIR.glob("*/results.json")):
            try:
                r = json.loads(p.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if r.get("status") == "completed":
                found[r["dataset_key"]] = r  # sorted by run id (timestamp) -> last wins
    return {"datasets": {k: found.get(k) for k in DATASETS}, "available": sorted(found), "not_run": [k for k in DATASETS if k not in found],
            "dataset_catalogue": DATASETS}


if __name__ == "__main__":  # python -m app.services.model_comparison_service
    res = run_all()
    for k, v in res.items():
        print(k, v.get("status"), v.get("run_id") or v.get("reason"))
    sys.exit(0 if all(v.get("status") == "completed" for v in res.values()) else 1)
