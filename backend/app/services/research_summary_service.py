"""Research Console landing summary. Every figure and finding is derived from stored records at request time; no result is typed in."""
from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from sqlalchemy.orm import Session

from app.services import (
    agent_evaluation_service,
    architecture_evaluation_service,
    causal_identification_service,
    llm_evaluation_status_service,
    model_comparison_service,
    research_overview_service,
    research_validation_service,
    risk_assessment_service,
)

EVIDENCE_LEGEND = [
    {"key": "measured", "label": "Measured", "meaning": "Calculated directly from recorded observations or experiment outputs."},
    {"key": "estimated", "label": "Estimated", "meaning": "Model-derived, with its assumptions stated."},
    {"key": "simulated", "label": "Simulated", "meaning": "Generated by an explicitly described simulation; describes the simulation's assumptions."},
    {"key": "not_evaluated", "label": "Not evaluated", "meaning": "Not run, or the data or method does not support it. Never shown as a zero."},
]


def _fmt(v: float, dp: int = 0) -> str:
    return f"{v:,.{dp}f}"


def get_summary(db: Session) -> dict[str, Any]:
    mc = model_comparison_service.latest_results()
    llm = llm_evaluation_status_service.build_status()
    val = research_validation_service.run_validation()
    agent_eval = agent_evaluation_service.get_agent_evaluation(db)
    arch = architecture_evaluation_service.get_architecture_evaluation(agent_eval)
    causal = causal_identification_service.get_report()
    ov = research_overview_service.build_overview(db)

    findings: list[dict] = []
    datasets: list[dict] = []
    stamps: list[str] = []

    for key, run in mc["datasets"].items():
        meta = mc["dataset_catalogue"][key]
        if not run:
            datasets.append({"name": meta["name"], "provenance": meta["provenance"], "observations": None, "period": None, "status": "not_evaluated"})
            continue
        stamps.append(run["created_utc"])
        datasets.append({"name": meta["name"], "provenance": meta["provenance"], "observations": run["n_usable_observations"],
                         "period": f"{run['period']['first']} to {run['period']['last']}", "status": "measured"})
        sel, base = run["selection"], run["models"][run["baseline"]["key"]]["test"]
        t = sel["test"]
        unit = meta["unit"]
        d = run["models"][sel["selected"]]["paired_vs_baseline"]
        lo, hi = d["ci95"]
        reliable = "the paired interval excludes 0" if (lo > 0 or hi < 0) else "the paired interval includes 0, so no reliable difference at this sample size"
        findings.append({
            "evidence": run["evidence_type"], "area": "Model comparison",
            "text": (f"{meta['name']}: of four learned models, {sel['selected_label']} was chosen by cross-validation; on the untouched test period "
                     f"({run['split']['test']['dates']} dates) its RMSE was {_fmt(t['rmse'], 1)} {unit} vs {_fmt(base['rmse'], 1)} for the seasonal-naive baseline "
                     f"({'better' if sel['beats_baseline_on_test_rmse'] else 'not better'}; {reliable})."),
            "source": run["run_id"]})

    primary = arch.get("primary_evidence")
    if primary:
        d_vs_b = next((c for c in primary["comparisons"] if c["contrast"] == "D_vs_B"), None)
        if d_vs_b and d_vs_b.get("mean_difference") is not None:
            direction = "higher (worse)" if d_vs_b["mean_difference"] > 0 else "lower (better)"
            findings.append({"evidence": "simulated", "area": "Architecture evaluation",
                             "text": (f"On {primary['design']['decisions_per_architecture']:,} simulated decisions per architecture, the full multi-agent system had {direction} regret than "
                                      f"the simulation alone (difference {d_vs_b['mean_difference']:+.3f}, 95% CI {d_vs_b['ci95'][0]:+.3f} to {d_vs_b['ci95'][1]:+.3f})."),
                             "source": "experiments/r1"})

    covs = llm.get("live_coverage") or []
    for cov in covs:
        who = "OpenAI" if cov["provider"] == "openai" else "TypeSafe Jev (earlier provider)" if cov["provider"] == "typesafe-jev" else cov["provider"]
        findings.append({"evidence": "measured", "area": f"LLM evaluation - {who}",
                         "text": (f"{cov['tasks_attempted_at_least_once']} of {cov['tasks_in_spec']} frozen tasks were attempted at least once with {cov['max_repeats_any_run']} of "
                                  f"{cov['repeats_frozen']} repeats; {cov['primary_correct_sum']} of {cov['primary_attempts_sum']} scored attempts were correct. "
                                  f"This is a single-attempt sample, not an accuracy estimate, and the frozen five-repeat benchmark is incomplete. Reported separately from other providers."),
                         "source": ", ".join(r["run_id"] for r in cov["runs"])})
    if not covs:
        findings.append({"evidence": "not_evaluated", "area": "LLM evaluation", "text": "No live evaluation run is stored.", "source": None})

    pairs = causal["assessment"]["pairs"]
    unsupported = [p for p in pairs if p["status"] == "unsupported"]
    sim = causal.get("known_truth_simulation")
    txt = f"{len(unsupported)} of {len(pairs)} candidate treatment-outcome pairs cannot be causally evaluated with the available data."
    if sim:
        s = sim["known_truth_simulation"]
        txt += (f" Under random assignment in synthetic data, the estimator recovered a promotion effect of {s['estimate_pct']:.1f}% "
                f"(95% CI {s['ci95_pct'][0]:.1f} to {s['ci95_pct'][1]:.1f}) against a documented {s['documented_truth_pct']:.0f}%.")
    findings.append({"evidence": "simulated" if sim else "not_evaluated", "area": "Causal evaluation", "text": txt, "source": sim["run_id"] if sim else None})

    churn = risk_assessment_service.latest_churn_calibration()
    if churn:
        m = churn["metrics"]
        findings.append({"evidence": churn["evidence_type"], "area": "Risk calibration",
                         "text": (f"Churn probabilities on {m['n']:,} held-out synthetic customers: Brier {m['brier']:.3f} vs {m['brier_baseline_prevalence']:.3f} for a prevalence-only "
                                  f"baseline, expected calibration error {m['ece']:.3f}. The decision risk score is not a probability and is not calibrated."),
                         "source": churn["run_id"]})
        stamps.append(churn["created_utc"])

    live_runs = llm.get("run_history") or []
    for r in live_runs:
        if r["kind"] == "live_evaluation" and r.get("finished_utc"):
            stamps.append(r["finished_utc"])

    n_algos = 0
    algos: list[str] = []
    for run in mc["datasets"].values():
        if run:
            for k, m in run["models"].items():
                if m["label"] not in algos:
                    algos.append(m["label"])
    n_algos = len(algos)

    measured_metrics = []
    for run in mc["datasets"].values():
        if run:
            measured_metrics = ["MAE", "RMSE", "R²", "MAPE (only when defined)", "paired bootstrap interval", "interval coverage"]
            break
    if llm.get("evaluated"):
        measured_metrics += ["task correctness vs ground truth", "latency", "token usage"]
    if churn:
        measured_metrics += ["Brier score", "log loss", "ROC-AUC", "expected calibration error"]

    return {
        "objective": ("Evaluate DecisionGPT's components in a controlled, reproducible way: how well forecasting models predict held-out sales, how an AI question-understanding "
                      "layer handles business questions, and whether the multi-step decision architecture improves decisions over simpler alternatives."),
        "datasets": datasets,
        "algorithms": algos, "n_algorithms": n_algos,
        "methodology": ["Chronological train / validation / test split on dates (test period untouched until final scoring)",
                        "Expanding-window time-series cross-validation for model selection",
                        "A simple seasonal-naive baseline that every model must beat",
                        "Fixed seeds, versioned run records and recorded software versions",
                        "Frozen LLM benchmark (27 tasks, ground truth computed independently from the data)"],
        "status": {"experiments_completed": ov.get("experiments_completed"), "experiments_failed": ov.get("experiments_failed"),
                   "model_comparison_runs": len(mc["available"]), "live_llm_runs": sum(1 for r in live_runs if r["kind"] == "live_evaluation"),
                   "validation_state": val["state"], "validation_counts": val["counts"]},
        "measured_metrics": measured_metrics,
        "key_findings": findings,
        "limitations": ["Real-data evidence is one store over 89 days; it is not representative of Indian SMEs.",
                        "Test periods are short, so error estimates are indicative.",
                        "Architecture results are simulated; no real business outcome has been collected.",
                        "The LLM evaluation is partial: one repeat per task; the five-repeat frozen benchmark is incomplete.",
                        "Causal effects can only be checked where assignment is random by design (synthetic data)."],
        "latest_verified_run": max(stamps) if stamps else None,
        "evidence_legend": EVIDENCE_LEGEND,
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
