"""Confirmatory aggregation across cells: Holm over the 6 (dataset, H) tests of H1 and, separately, of H2; writes ``results/CONFIRMATORY_SUMMARY.json`` and ``.md``.

``python -m research.forecast_study_v1.aggregate``  (reads ``<cell>/analysis.json`` of the 6 full cells; a missing cell is reported as NOT RUN, not imputed).
"""
from __future__ import annotations

import json
from pathlib import Path

from research.forecast_study_v1 import inference as inf

RESULTS = Path(__file__).resolve().parent / "results"
CELLS = [f"fs1_{d}_H{h}" for d in ("m5_ca1", "m5_tx1", "or2_top100") for h in (28, 7)]
ALPHA = 0.05


def fmt(x, p=3):
    return "n/a" if x is None else f"{x:.{p}f}"


def main() -> dict:
    ana = {}
    for c in CELLS:
        f = RESULTS / c / "analysis.json"
        if f.exists():
            ana[c] = json.load(open(f, encoding="utf-8"))
    out = {"cells_run": sorted(ana), "cells_not_run": [c for c in CELLS if c not in ana], "alpha": ALPHA, "families": {}}
    lines = ["# Confirmatory summary (generated by aggregate.py)", "", f"Cells run: {len(ana)}/6. Not run: {', '.join(out['cells_not_run']) or 'none'}.", ""]
    for key, label in (("H1_vs_matched_reference", "H1: primary model vs best-validation MATCHED-information baseline"),
                       ("H2_vs_any_reference", "H2: primary model vs best-validation baseline of ANY information set")):
        raw = {c: a[key]["p_two_sided"] for c, a in ana.items()}
        adj = inf.holm(raw)
        rows = {}
        lines += [f"## {label}", "", "| cell | model | reference | WAPE ref | WAPE model | rel. improvement [95% CI] | blocks won | raw p | Holm p | verdict |", "|---|---|---|---|---|---|---|---|---|---|"]
        for c, a in ana.items():
            r = a[key]
            holm_ok = adj[c] is not None and adj[c] < ALPHA
            verdict = r["decision_rule_H"] if r["decision_rule_H"] != "SUPPORTED" or holm_ok else "INCONCLUSIVE (Holm p >= 0.05)"
            rows[c] = {"estimate": r["estimate"], "ci95": r["ci95"], "raw_p": r["p_two_sided"], "holm_p": adj[c], "verdict": verdict, "model_wins_blocks": r["model_wins_blocks"],
                       "model": a["primary"], "reference": r["baseline"], "wape_model": r["wape_model"], "wape_reference": r["wape_baseline"]}
            lines.append(f"| {c} | {a['primary'].replace('pred__', '')} | {r['baseline'].replace('base__', '')} | {fmt(r['wape_baseline'])} | {fmt(r['wape_model'])} | "
                         f"{fmt(100 * r['estimate'], 1)}% [{fmt(100 * r['ci95'][0], 1)}, {fmt(100 * r['ci95'][1], 1)}] | {r['model_wins_blocks']}/{r['n_blocks']} | {fmt(r['p_two_sided'], 4)} | {fmt(adj[c], 4)} | {verdict} |")
        lines.append("")
        out["families"][key] = rows
    (RESULTS / "CONFIRMATORY_SUMMARY.json").write_text(json.dumps(out, indent=2), encoding="utf-8")
    (RESULTS / "CONFIRMATORY_SUMMARY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    o = main()
    print(json.dumps({"cells_run": o["cells_run"], "cells_not_run": o["cells_not_run"]}))
