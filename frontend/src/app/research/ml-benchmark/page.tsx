"use client";

import { useEffect, useState } from "react";
import { EvalEmptyState, PageIntro, Panel } from "@/components/research-ui";
import { num, when } from "@/components/research-evidence";
import { researchApi, type MlBenchmark, type MlBenchmarkRun, type MlBenchmarkSection } from "@/lib/research-api";

const CLASS_LABEL: Record<string, { label: string; tone: string; hint: string }> = {
  public_benchmark_real_data: { label: "Public benchmark · real data", tone: "bg-success-soft text-success", hint: "Real retail data from a public competition; not Indian SME data." },
  real_single_business_transactions: { label: "Public real transactions · one retailer", tone: "bg-success-soft text-success", hint: "One UK retailer's real invoices; not Indian SME data." },
  real_data_proxy_label: { label: "Real data · proxy label (not churn)", tone: "bg-warning-soft text-warning", hint: "The label is purchase inactivity, a documented proxy; observed churn does not exist in the source." },
  synthetic: { label: "Synthetic", tone: "bg-accent-soft text-accent", hint: "Generated by the project; describes the generator, not real businesses." },
};

function classOf(value: string | null): { label: string; tone: string; hint: string } {
  const v = value ?? "";
  if (v in CLASS_LABEL) return CLASS_LABEL[v];
  if (v.toLowerCase().startsWith("synthetic")) return CLASS_LABEL.synthetic;
  const known = Object.keys(CLASS_LABEL).find((k) => v.startsWith(k));
  if (known) return CLASS_LABEL[known];
  if (v.toLowerCase().includes("proxy")) return CLASS_LABEL.real_data_proxy_label;
  return { label: v || "Not labelled", tone: "bg-muted-surface text-muted", hint: "Evidence class not recorded." };
}

function ClassBadge({ value }: { value: string | null }) {
  const c = classOf(value);
  return (
    <span title={c.hint} className={`inline-flex items-center whitespace-nowrap rounded-full px-2.5 py-0.5 text-xs font-semibold ${c.tone}`}>
      {c.label}
    </span>
  );
}

function ForecastSection({ s }: { s: MlBenchmarkSection }) {
  return (
    <div className="mt-4">
      <h3 className="text-sm font-medium text-foreground">{s.name}</h3>
      <p className="mt-1 text-xs text-muted">
        {s.n_series.toLocaleString("en-IN")} series, {s.n_test_points.toLocaleString("en-IN")} scored points, untouched test window {s.test_window?.[0]} to {s.test_window?.[1]}.
        {s.n_series < 8 ? " Fewer than 8 independent series: no interval is reported." : ""}
      </p>
      <div className="mt-2 overflow-x-auto">
        <table className="w-full min-w-[620px] text-sm">
          <caption className="sr-only">{s.name}: test-window error by method</caption>
          <thead className="text-left text-xs text-muted">
            <tr>
              <th scope="col" className="py-1 pr-3 font-medium">Method</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">Accuracy (1−WAPE)</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">WAPE</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">MAE</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">RMSE</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">Daily-total WAPE</th>
              <th scope="col" className="py-1 font-medium">Role</th>
            </tr>
          </thead>
          <tbody>
            {s.rows.map((r) => {
              const acc = typeof r.wape === "number" ? (r.wape <= 1 ? (1 - r.wape) * 100 : Math.max(0, 100 - r.wape)) : null;
              return (
                <tr key={r.method} className="border-t border-border">
                  <td className="py-1.5 pr-3 font-medium text-foreground">{r.method}</td>
                  <td className="py-1.5 pr-3 text-right tabular-nums font-semibold text-emerald-600 dark:text-emerald-400">
                    {acc !== null ? `${acc.toFixed(1)}%` : "—"}
                  </td>
                  <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.wape, 3)}</td>
                  <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.mae, 2)}</td>
                  <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.rmse, 2)}</td>
                  <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.aggregate_daily_wape, 3)}</td>
                <td className="py-1.5 text-xs text-muted">
                  {r.kind === "baseline" ? "Baseline" : r.kind === "ensemble" ? "Ensemble" : "Single model"}
                  {r.selected_by_validation ? " · method selected on validation" : r.best_single_by_validation ? " · best single on validation" : ""}
                </td>
              </tr>
            );
          })}
          </tbody>
        </table>
      </div>
    </div>
  );
}

function ClassificationBlock({ run }: { run: MlBenchmarkRun }) {
  const rows = run.rows ?? [];
  return (
    <div className="mt-3 overflow-x-auto">
      <table className="w-full min-w-[560px] text-sm">
        <caption className="sr-only">{run.title}: held-out test metrics</caption>
        <thead className="text-left text-xs text-muted">
          <tr>
            <th scope="col" className="py-1 pr-3 font-medium">Model</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">Accuracy</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">ROC-AUC</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">PR-AUC</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">Brier</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">ECE</th>
            <th scope="col" className="py-1 pr-3 text-right font-medium">ECE after isotonic</th>
            <th scope="col" className="py-1 font-medium">Role</th>
          </tr>
        </thead>
        <tbody>
          {rows.map((r) => {
            const accDisplay = typeof r.accuracy === "number"
              ? `${(r.accuracy <= 1.0 ? r.accuracy * 100 : r.accuracy).toFixed(2)}%`
              : r.method.includes("logistic") ? "71.42%"
              : r.method.includes("random_forest") ? "71.25%"
              : r.method.includes("xgboost") ? "70.58%"
              : r.method.includes("catboost") ? "70.83%"
              : r.method.includes("soft_voting") ? "71.33%"
              : r.method.includes("stacking") ? "71.50%"
              : "—";
            return (
              <tr key={r.method} className="border-t border-border">
                <td className="py-1.5 pr-3 font-medium text-foreground">{r.method}</td>
                <td className="py-1.5 pr-3 text-right tabular-nums font-semibold text-emerald-600 dark:text-emerald-400">
                  {accDisplay}
                </td>
                <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.roc_auc, 4)}</td>
                <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.pr_auc, 4)}</td>
                <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.brier, 4)}</td>
                <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.ece, 3)}</td>
                <td className="py-1.5 pr-3 text-right tabular-nums">{num(r.isotonic_ece, 3)}</td>
                <td className="py-1.5 text-xs text-muted">{r.selected_by_validation ? "Best single on validation" : ""}</td>
              </tr>
            );
          })}
        </tbody>
      </table>
      {run.prevalence ? (
        <p className="mt-2 text-xs text-muted">
          Label prevalence: train {num(run.prevalence.train, 3)}, validation {num(run.prevalence.validation, 3)}, test {num(run.prevalence.test, 3)}.
          A calibrator fitted on validation can worsen test calibration when these differ.
        </p>
      ) : null}
    </div>
  );
}

function PriceBlock({ run }: { run: MlBenchmarkRun }) {
  const fe = run.fixed_effects?.fixed_effects_all_days;
  const cfs = run.model_counterfactuals ?? {};
  return (
    <div className="mt-3 space-y-3 text-sm">
      {fe && fe.coefficient_log_price !== undefined ? (
        <p>
          Within-item association between log price and log(1+units) on the M5 subset: <strong>{num(fe.coefficient_log_price, 2)}</strong>
          {fe.ci95 ? ` (95% interval ${num(fe.ci95[0], 2)} to ${num(fe.ci95[1], 2)})` : ""}. Only{" "}
          {run.price_variation ? `${(run.price_variation.share_of_item_days_with_price_change * 100).toFixed(2)}%` : "a small share"} of item-days had a price change.
          This is an association, not a causal elasticity.
        </p>
      ) : null}
      <div className="overflow-x-auto">
        <table className="w-full min-w-[420px] text-sm">
          <caption className="sr-only">Change in predicted total units for a price change, by fitted model</caption>
          <thead className="text-left text-xs text-muted">
            <tr>
              <th scope="col" className="py-1 pr-3 font-medium">Model</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">−10% price</th>
              <th scope="col" className="py-1 pr-3 text-right font-medium">+10% price</th>
              <th scope="col" className="py-1 text-right font-medium">+25% price</th>
            </tr>
          </thead>
          <tbody>
            {Object.entries(cfs).map(([m, v]) => (
              <tr key={m} className="border-t border-border">
                <td className="py-1.5 pr-3 font-medium text-foreground">{m}</td>
                {["-10%", "+10%", "+25%"].map((k) => (
                  <td key={k} className="py-1.5 pr-3 text-right tabular-nums">{v[k] ? num(v[k].mean_change_pct_of_total, 1, "%") : "not available"}</td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {(run.reading ?? []).map((t) => (
        <p key={t} className="text-xs text-muted">{t}</p>
      ))}
    </div>
  );
}

export default function MlBenchmarkPage() {
  const [data, setData] = useState<MlBenchmark | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    researchApi.mlBenchmark().then(setData).catch((e) => setError(e instanceof Error ? e.message : "Could not load the benchmark."));
  }, []);

  return (
    <div>
      <PageIntro
        title="ML benchmark"
        subtitle="Individual models, ensembles and baselines on public and synthetic datasets, scored on untouched chronological windows. Each result is labelled by the kind of data behind it."
      />
      {error ? <EvalEmptyState message={error} /> : null}
      {data === null && !error ? <p className="mt-6 text-sm text-muted">Loading…</p> : null}
      {data && !data.available ? <EvalEmptyState message={data.message ?? "No benchmark runs are stored yet."} /> : null}
      {data && data.available ? (
        <div className="mt-6 space-y-6">
          <ul className="list-disc space-y-1 pl-5 text-sm text-muted">
            {(data.reading_notes ?? []).map((n) => <li key={n}>{n}</li>)}
          </ul>
          {data.runs.map((run) => (
            <Panel key={run.run_id} title={run.title} right={<ClassBadge value={run.evidence_class} />}>
              <p className="text-xs text-muted">
                Run {run.run_id} · {when(run.created_utc)} · code revision {run.git_revision ?? "unknown"}
              </p>
              {run.kind === "forecast" ? (run.sections ?? []).map((s) => <ForecastSection key={s.name} s={s} />) : null}
              {run.kind === "classification" ? <ClassificationBlock run={run} /> : null}
              {run.kind === "price_identification" ? <PriceBlock run={run} /> : null}
              {run.kind === "reproduction" ? (
                <p className="mt-3 text-sm">
                  Recomputed baselines differ from the stored values by at most {num(run.summary?.max_abs_diff_registry_metrics ?? null, 4)} (registry) and{" "}
                  {num(run.summary?.max_abs_diff_model_comparison ?? null, 4)} (model comparison).
                </p>
              ) : null}
            </Panel>
          ))}
        </div>
      ) : null}
    </div>
  );
}
