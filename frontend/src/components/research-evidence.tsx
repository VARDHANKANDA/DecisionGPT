"use client";

import type { ReactNode } from "react";
import type { EvidenceType } from "@/lib/research-api";

/** Evidence type is always shown as a word plus a symbol, never by colour alone. */
const EVIDENCE: Record<string, { symbol: string; label: string; tone: string; hint: string }> = {
  measured: { symbol: "▲", label: "Measured", tone: "bg-success-soft text-success", hint: "Calculated directly from recorded observations or experiment outputs." },
  measured_on_synthetic_data: {
    symbol: "▲",
    label: "Measured on synthetic data",
    tone: "bg-accent-soft text-accent",
    hint: "Calculated from recorded outputs, but the data were generated by the project, so it describes the generator rather than real businesses.",
  },
  estimated: { symbol: "≈", label: "Estimated", tone: "bg-accent-soft text-accent", hint: "Model-derived, with assumptions stated." },
  simulated: { symbol: "◇", label: "Simulated", tone: "bg-warning-soft text-warning", hint: "Generated by an explicitly described simulation; it describes the simulation's assumptions." },
  not_evaluated: { symbol: "○", label: "Not evaluated", tone: "bg-muted-surface text-muted", hint: "Not run, or the data or method does not support it. Never shown as a zero." },
};

export function EvidenceTypeBadge({ type }: { type: EvidenceType | string }) {
  const e = EVIDENCE[type] ?? EVIDENCE.not_evaluated;
  return (
    <span title={e.hint} className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full px-2.5 py-0.5 text-xs font-semibold ${e.tone}`}>
      <span aria-hidden="true">{e.symbol}</span>
      {e.label}
    </span>
  );
}

const CHECK: Record<string, { symbol: string; label: string; tone: string }> = {
  passed: { symbol: "✓", label: "Passed", tone: "bg-success-soft text-success" },
  failed: { symbol: "✕", label: "Failed", tone: "bg-danger-soft text-danger" },
  warning: { symbol: "!", label: "Warning", tone: "bg-warning-soft text-warning" },
  not_applicable: { symbol: "–", label: "Not applicable", tone: "bg-muted-surface text-muted" },
};

export function CheckStatusBadge({ status }: { status: string }) {
  const c = CHECK[status] ?? CHECK.not_applicable;
  return (
    <span className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full px-2.5 py-0.5 text-xs font-semibold ${c.tone}`}>
      <span aria-hidden="true">{c.symbol}</span>
      {c.label}
    </span>
  );
}

export function EvidenceLegend() {
  return (
    <ul className="grid gap-2 sm:grid-cols-2 lg:grid-cols-4" aria-label="Evidence types">
      {(["measured", "estimated", "simulated", "not_evaluated"] as const).map((k) => (
        <li key={k} className="rounded-xl border border-border bg-surface p-3">
          <EvidenceTypeBadge type={k} />
          <p className="mt-1.5 text-xs text-muted">{EVIDENCE[k].hint}</p>
        </li>
      ))}
    </ul>
  );
}

/** A number, or an explicit "not available" - a missing value is never rendered as 0. */
export function num(v: number | null | undefined, dp = 2, unit = ""): string {
  if (v === null || v === undefined || Number.isNaN(v)) return "not available";
  return `${v.toLocaleString("en-IN", { minimumFractionDigits: dp, maximumFractionDigits: dp })}${unit}`;
}

export function pct(v: number | null | undefined, dp = 1): string {
  if (v === null || v === undefined || Number.isNaN(v)) return "not available";
  return `${v.toFixed(dp)}%`;
}

export function when(v: string | null | undefined): string {
  if (!v) return "not available";
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? v : d.toLocaleString("en-GB", { dateStyle: "medium", timeStyle: "short", timeZone: "UTC" }) + " UTC";
}

export function Definition({ term, children }: { term: string; children: ReactNode }) {
  return (
    <div>
      <dt className="text-sm font-medium text-foreground">{term}</dt>
      <dd className="mt-0.5 text-sm text-muted">{children}</dd>
    </div>
  );
}

export function SectionTitle({ children, hint }: { children: ReactNode; hint?: string }) {
  return (
    <div className="mb-2">
      <h2 className="text-base font-semibold text-foreground">{children}</h2>
      {hint ? <p className="text-sm text-muted">{hint}</p> : null}
    </div>
  );
}

/** Horizontal bar for values that share one unit and scale. */
export function Bar({ value, max, label, note }: { value: number; max: number; label: string; note?: string }) {
  const w = max > 0 ? Math.max(2, Math.min(100, (value / max) * 100)) : 0;
  return (
    <div className="grid grid-cols-[minmax(0,9rem)_1fr_auto] items-center gap-3 text-sm sm:grid-cols-[14rem_1fr_auto]">
      <span className="truncate text-foreground" title={label}>
        {label}
      </span>
      <span className="h-3 rounded-full bg-muted-surface">
        <span className="block h-3 rounded-full bg-accent" style={{ width: `${w}%` }} />
      </span>
      <span className="tabular-nums text-foreground">
        {value.toLocaleString("en-IN", { maximumFractionDigits: 3 })}
        {note ? <span className="ml-1 text-xs text-muted">{note}</span> : null}
      </span>
    </div>
  );
}
