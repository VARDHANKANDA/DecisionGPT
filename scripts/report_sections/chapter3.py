"""
Chapter 3: Proposed System and Requirements (Full University Thesis Edition).
Comprehensive requirements engineering detailing the Dual-Plane solution,
formal functional & non-functional requirements, RBAC permission matrix,
use-case specifications, use-case diagram (Figure 3.1), and operational workflows.
"""

from docx.shared import Pt, Inches
from report_sections.common import (
    add_chapter_header, add_heading_1, add_heading_2, add_p,
    add_tbl_caption, add_table_data, add_image_safe, add_fig_caption
)

def build_chapter_3(doc):
    add_chapter_header(doc, 3, "PROPOSED SYSTEM AND REQUIREMENTS")

    add_heading_1(doc, "3.1 Proposed Solution: The Dual-Plane Architecture")
    add_p(
        doc,
        "To resolve the tension between ungrounded generative language models and rigid descriptive BI dashboards, DecisionGPT implements a Dual-Plane Architecture that decouples quantitative mathematical computation from qualitative reasoning:"
    )
    add_p(
        doc,
        "1. Quantitative Mathematical Execution Plane: This layer encapsulates all numerical processing, statistical feature engineering, machine learning pipelines, causal DAG adjustments, and discrete-event digital twin simulations. This execution core operates completely independently of generative language models. Every financial figure, demand forecast, inventory stock level, and liquidity trajectory is generated by verified, deterministic code with explicit mathematical guarantees, eliminating the risk of numerical hallucination [25], [34]."
    )
    add_p(
        doc,
        "2. Cognitive Reasoning and Governance Plane: This layer organizes language models and structured rule sets into specialized agent personas. The agents interpret deterministic simulation outputs, analyze cross-functional trade-offs, conduct structured evaluations across competing business perspectives, and generate human-readable executive briefs that are validated against verified database facts before display [30], [39]."
    )
    add_p(
        doc,
        "By enforcing this clean boundary, DecisionGPT ensures that human decision-makers receive both the computational precision of predictive analytics and the accessible, multi-perspective synthesis of specialist advisors."
    )

    add_heading_1(doc, "3.2 Stakeholder Personas and Operational Roles")
    add_p(
        doc,
        "DecisionGPT is designed to support four primary enterprise user roles, reflecting standard operating responsibilities in commercial SMEs:"
    )
    add_p(
        doc,
        "• SME Business Owner / Managing Director: Responsible for overall business solvency, capital allocation, and final approval of strategic recommendations. Requires high-level KPI summaries, forward-looking cash-flow projections, and clear trade-off explanations before committing capital."
    )
    add_p(
        doc,
        "• Financial Planning Analyst / Accountant: Focuses on gross margins, operating expenses, working capital runway, and supplier payment schedules. Interacts with the scenario simulator and digital twin to test cost shocks and price sensitivity."
    )
    add_p(
        doc,
        "• Operations / Inventory Manager: Manages stock levels, reorder quantities, delivery lead times, and fulfillment bottlenecks. Uses multi-horizon demand forecasting to establish safety stock levels and avoid stockouts."
    )
    add_p(
        doc,
        "• System Administrator: Manages tenant registration, user role assignments, database connection parameters, and immutable system audit logs."
    )

    add_heading_1(doc, "3.3 Functional Requirements Specification")
    add_p(
        doc,
        "The functional capabilities of DecisionGPT are formally defined across eight modular requirements (FR1 through FR8):"
    )
    add_p(
        doc,
        "• FR1 — Guided Data Ingestion and Hygiene: The system must allow users to upload tabular transaction files (CSV, Parquet, JSON), automatically infer column schemas, impute missing values using median/mode strategies, clip extreme numerical outliers via IQR winsorization, and store cleaned canonical datasets under tenant-scoped isolation."
    )
    add_p(
        doc,
        "• FR2 — Multi-Horizon Demand Forecasting: The system must train and evaluate GBDT regression models (HistGradientBoosting, Random Forest, XGBoost) to predict future sales volume across daily (1-day), bi-weekly (14-day), and monthly (28-day) horizons using rolling-origin temporal validation, computing WAPE and volume-weighted Forecast Scores."
    )
    add_p(
        doc,
        "• FR3 — Causal Intervention Modeling: The system must integrate a structural causal DAG to adjust for observed confounding variables (such as seasonal demand and baseline product popularity) when evaluating marketing promotions or price modifications."
    )
    add_p(
        doc,
        "• FR4 — Discrete-Event State-Space Simulation: The system must provide a digital twin simulation engine that models cash balance, inventory, and order queues as dynamic state variables, projecting multi-week operational trajectories and computing insolvency ruin probabilities under simulated shocks."
    )
    add_p(
        doc,
        "• FR5 — Specialized Agent Consultations: The system must provide dedicated workspaces for five specialist agents (Business Analyst, Financial Advisor, Marketing Advisor, Risk Manager, Strategy Optimiser), each analyzing operational data according to its domain mandate."
    )
    add_p(
        doc,
        "• FR6 — Structured Multi-Agent Debate Workspace: The system must orchestrate a 7-stage rule-based debate workspace where specialists review shared evidence, generate cross-challenges, assess assumptions, and synthesize balanced strategic recommendations."
    )
    add_p(
        doc,
        "• FR7 — Guarded Business Assistant: The system must provide a conversational query interface that translates natural language business questions into structured analytical queries, verifies generated summaries against factual SQL results, and refuses to guess when data is insufficient."
    )
    add_p(
        doc,
        "• FR8 — Strategic Decision Governance: The system must maintain an immutable decision log tracking business goals, alternative strategies considered, agent evaluations, simulation trajectories, human approvals, and outcome reviews."
    )

    add_heading_1(doc, "3.4 Non-Functional Requirements Specification")
    add_p(
        doc,
        "System reliability, security, and performance are governed by four non-functional requirements (NFR1 through NFR4):"
    )
    add_p(
        doc,
        "• NFR1 — Mathematical Determinism: All calculations, forecasting metrics, simulation state transitions, and tabular aggregations must execute through verified deterministic libraries without LLM approximation."
    )
    add_p(
        doc,
        "• NFR2 — Multi-Tenant Data Isolation: Every database entity, uploaded dataset, and analytical cache must be strictly scoped by business_id. The system must reject cross-tenant data leakage at the API middleware level."
    )
    add_p(
        doc,
        "• NFR3 — Computational Latency: Standard analytical queries and KPI dashboards must load in under 1.5 seconds. Long-running tasks, such as 100-episode Monte Carlo simulations or 7-stage agent debates, must execute asynchronously within 30 seconds."
    )
    add_p(
        doc,
        "• NFR4 — Auditability and Reproducibility: Every recommendation must record its complete provenance—including the source dataset version, model parameters, simulation seeds, and agent evaluation results—to support full retrospective review."
    )

    add_heading_1(doc, "3.5 Role-Based Access Control Specification")
    add_p(
        doc,
        "To enforce operational security, access privileges are partitioned across user roles in Table 3.1."
    )

    add_tbl_caption(doc, "3.1", "Role-Based Access Control (RBAC) Permission Matrix")

    rbac_headers = ["Functional Domain / Action", "Administrator", "Business Owner", "Financial Analyst", "Operations Manager"]
    rbac_data = [
        ["Tenant Account Management", "Full Access (CRUD)", "No Access", "No Access", "Read-Only"],
        ["Dataset Ingestion & Cleaning", "Full Access", "Full Access", "Full Access", "Read-Only"],
        ["Business Analytics Explorer", "Full Access", "Full Access", "Full Access", "Full Access"],
        ["Sales Demand Forecasting", "Full Access", "Full Access", "Full Access", "Full Access"],
        ["Digital Twin Scenario Simulation", "Full Access", "Full Access", "Full Access", "Full Access"],
        ["Multi-Agent Swarm Debate Initiation", "Full Access", "Full Access", "Full Access", "No Access"],
        ["Strategic Decision Sign-off", "Full Access", "Sign-off Authority", "Sign-off Authority", "Read-Only"],
        ["System Audit Logs & Traceability", "Full Access", "Read-Only", "Read-Only", "No Access"]
    ]
    add_table_data(doc, rbac_headers, rbac_data, col_widths=[2.1, 1.0, 1.0, 1.0, 1.0])

    add_heading_1(doc, "3.6 Use Case Modeling and System Specifications")
    add_p(
        doc,
        "The interaction between enterprise users and DecisionGPT is formally modeled across six core use cases (UC1 through UC6), summarized in Table 3.2 and illustrated in Figure 3.1."
    )

    add_tbl_caption(doc, "3.2", "System Use-Case Specifications (UC1 - UC6)")

    uc_headers = ["Use Case ID", "Use Case Title", "Primary Actor", "Preconditions", "Postconditions"]
    uc_data = [
        ["UC1", "Ingest & Preprocess Dataset", "Operations Manager", "Raw CSV/Parquet file available", "Clean canonical dataset persisted in storage"],
        ["UC2", "Generate Demand Forecasts", "Financial Planner", "Historical sales records ingested", "1D/14D/28D multi-horizon forecast models deployed"],
        ["UC3", "Run Causal What-If Simulation", "Financial Planner", "Prepared dataset & causal DAG loaded", "Monte Carlo cash-flow & ruin probabilities generated"],
        ["UC4", "Conduct Multi-Agent Debate", "Operations Manager", "Simulated strategy alternatives defined", "Dialectical consensus & executive brief synthesized"],
        ["UC5", "Review & Commit Strategic Decision", "Executive / Owner", "Debate brief & twin metrics reviewed", "Decision logged in immutable audit repository"],
        ["UC6", "Manage Enterprise RBAC & Settings", "Administrator", "Valid administrative credentials", "Organization profile & user privileges updated"]
    ]
    add_table_data(doc, uc_headers, uc_data, col_widths=[0.8, 1.5, 1.2, 1.3, 1.3])

    add_p(
        doc,
        "Figure 3.1 illustrates the Unified Modeling Language (UML) Use-Case Diagram for DecisionGPT, delineating actor boundaries, system operations, and relational dependencies."
    )

    add_image_safe(doc, "figure_use_case.png", width=Inches(5.8))
    add_fig_caption(doc, "3.1", "DecisionGPT System Use-Case Specification Diagram")

    add_heading_1(doc, "3.7 Operational Data and Decision Life Cycle")
    add_p(
        doc,
        "The operational lifecycle in DecisionGPT moves through five sequential phases: (1) Ingestion and Cleaning, where raw tabular records are validated, imputed, and transformed into canonical schemas; (2) Predictive Analytics, where GBDT algorithms generate multi-horizon forecasts and churn risk estimates; (3) Dynamic Simulation, where the digital twin projects cash-flow and inventory states under simulated operational shocks; (4) Multi-Perspective Review, where specialist agents evaluate trade-offs and enforce downside risk bounds; and (5) Executive Governance, where human managers inspect recommendations and commit approved decisions to an auditable historical log."
    )

    doc.add_page_break()
